    public void loadPatients(UserController usrCtrl) {
        DefaultTableModel model = (DefaultTableModel) patientTable.getModel();
        model.setRowCount(0);
//        UserManagement usrServices = this.usrCtrl.getUserServices();
        List<User> allUsers = UserManagement.getAllUsers();
        for (User usr: allUsers) {
            LocalDate date = DateTime.getDate(DateTime.toDateTimeObject(usr.getJoinedDateTime()));
            String joinedDate = DateTime.toDateStringWords(date);
            String[] patientData = {usr.getId(), WordProcessing.capitalizeEachWord(usr.getName()), joinedDate};
            model.addRow(patientData);
        }
//        userTable = new JTable(model);
    }

