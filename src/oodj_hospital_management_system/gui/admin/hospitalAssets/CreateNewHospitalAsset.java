    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed
        if (nameField.getText().isEmpty()) {
            JOptionPane.showConfirmDialog(parent, "Missing Name Field", "Create Asset Failed", JOptionPane.ERROR_MESSAGE);
            nameField.requestFocusInWindow();
            nameField.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.RED));
        } else if (locationField.getText().isEmpty()) {
            JOptionPane.showConfirmDialog(parent, "Missing Location Field", "Create Asset Failed", JOptionPane.ERROR_MESSAGE);
            locationField.requestFocusInWindow();
            locationField.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.RED));
        } else if (countWords(locationField.getText()) > LOCATION_WORD_LIMIT) {
            JOptionPane.showConfirmDialog(parent,
                    "Location must not exceed " + LOCATION_WORD_LIMIT + " words",
                    "Create Asset Failed", JOptionPane.ERROR_MESSAGE);
            locationField.requestFocusInWindow();
            locationField.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.RED));
        } else if (countWords(descriptionField.getText()) > DESCRIPTION_WORD_LIMIT) {
            JOptionPane.showConfirmDialog(parent,
                    "Description must not exceed " + DESCRIPTION_WORD_LIMIT + " words",
                    "Create Asset Failed", JOptionPane.ERROR_MESSAGE);
            descriptionField.requestFocusInWindow();
            descriptionField.setBorder(javax.swing.BorderFactory.createLineBorder(java.awt.Color.RED));
        } else {
            // assetId, assetType, assetName, imagePath, location, description, totalBeds
            String assetType = (String) typeField.getSelectedItem();
            LinkedHashMap<String, String> msg = this.usrCtrl.getHospitalAssetController().createHospitalAsset(assetType, nameField.getText(), imageField.getText(), locationField.getText(), descriptionField.getText());
            User newUsr = UserManagement.getUserById(msg.get("newUserId"));
            if (newUsr != null) {
                JOptionPane.showMessageDialog(this, String.format("New User ('%s', '%s') is created!", newUsr.getId(), newUsr.getName()));
                String newUsrPwd = newUsr.getPwd();
                // IMPORTANT !!!!!!!!!!!!! i wanna add send email~~~~
                String showNewUsr = String.format("User ID: %s\nUser Password: %s\n\nPlease notfy the user to update the password for security", newUsr.getId(), newUsr.getPwd());
                JOptionPane.showMessageDialog(this, showNewUsr, "New User Credentials", JOptionPane.INFORMATION_MESSAGE);
                this.refreshTable.run();
                dispose();
            } else {
                JOptionPane.showMessageDialog(this, String.format("Fail to create new User '%s' :(\n", nameField.getText()) + msg.get("msg"), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_createButtonActionPerformed

