    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        String keyword = searchField.getText();
        List<HospitalAsset> searchResults = this.usrCtrl.getHospitalAssetController().searchHospitalAssets(keyword);
        searchResults = getLabAssetsOnly(searchResults);
        currentAssets = searchResults;
        renderAssets(searchResults);
        updateResultLabel("Showing results for \"" + keyword + "\"", searchResults.size());
    }//GEN-LAST:event_searchButtonActionPerformed

    private void sortFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_sortFieldActionPerformed
        if (currentAssets == null || currentAssets.isEmpty()) return;

        List<HospitalAsset> sorted = new java.util.ArrayList<>(currentAssets);
        switch (sortField.getSelectedIndex()) {
            case 1: // ID
                sorted.sort(java.util.Comparator.comparing(HospitalAsset::getAssetId));
                break;
            case 2: // Name
                sorted.sort(java.util.Comparator.comparing(HospitalAsset::getAssetName));
                break;
            default: // Default -> reload unsorted
                loadAssets();
                return;
        }
        currentAssets = sorted;
        renderAssets(sorted);
    }//GEN-LAST:event_sortFieldActionPerformed

    private void filterByFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_filterByFieldActionPerformed
        String selected = (String) filterByField.getSelectedItem();

        if ("Status".equals(selected)) {
            List<HospitalAsset> labAssets = getLabAssetsOnly(HospitalAssetManagement.getAllHospitalAssets());

            String[] statusOptions = {
                HospitalAsset.STATUS_AVAILABLE,
                HospitalAsset.STATUS_OCCUPIED,
                HospitalAsset.STATUS_MAINTENANCE,
                HospitalAsset.STATUS_INACTIVE
            };

            String chosenStatus = (String) JOptionPane.showInputDialog(
                    parentWindow,
                    "Select a status to filter by:",
                    "Filter by Status",
                    JOptionPane.PLAIN_MESSAGE,
                    null,
                    statusOptions,
                    statusOptions[0]
            );

            if (chosenStatus == null) {
                filterByField.setSelectedIndex(0);
                return;
            }

            List<HospitalAsset> filtered = labAssets.stream()
                    .filter(a -> chosenStatus.equals(a.getStatus()))
                    .collect(java.util.stream.Collectors.toList());

            currentAssets = filtered;
            renderAssets(filtered);
            updateResultLabel("Showing assets with status \"" + chosenStatus + "\"", filtered.size());
        } else {
            loadAssets();
        }
    }//GEN-LAST:event_filterByFieldActionPerformed

